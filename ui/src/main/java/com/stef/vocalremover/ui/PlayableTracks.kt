data class PlayableTrack(
    val title: String,
    val duration: String
)

@Composable
fun PlayableTracks(
    tracks: List<PlayableTrack>,
    modifier: Modifier = Modifier
) {
    LazyColumn(
        modifier = modifier,
        contentPadding = PaddingValues(20.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        items(tracks) { track ->
            PlayableTrackCard(track = track)
        }
    }
}

@Composable
private fun PlayableTrackCard(track: PlayableTrack) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surfaceContainerLow
        )
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 18.dp, vertical = 16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Column(
                modifier = Modifier.weight(1f),
                verticalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                Text(
                    text = track.title,
                    style = MaterialTheme.typography.titleMedium
                )
                Text(
                    text = track.duration,
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
            Spacer(Modifier.width(16.dp))
            Surface(
                modifier = Modifier.size(44.dp),
                shape = CircleShape,
                color = MaterialTheme.colorScheme.primaryContainer
            ) {
                Box(
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = "▶",
                        style = MaterialTheme.typography.labelLarge,
                        color = MaterialTheme.colorScheme.onPrimaryContainer
                    )
                }
            }
        }
    }
}

private val previewTracks = listOf(
    PlayableTrack(title = "Brano 1", duration = "3:42"),
    PlayableTrack(title = "Brano 2", duration = "4:08"),
    PlayableTrack(title = "Brano 3", duration = "2:56")
)

@Preview(showBackground = true)
@Composable
private fun PlayableTracksPreview() {
    MaterialTheme {
        PlayableTracks(tracks = previewTracks)
    }
}
